package JavaKeywords;

public class Break {
	public static void main(String[] args) {
		int i=0;
		while(i<10) {
			System.out.println(i);
			i++;
			if(i == 4) {
				break;
				
			}System.out.println(i);
		}
	}

}

//The break keyword is used to break out a for loop, a while loop or a switch block.
