package com.java.InterviewPrograms;

public class SwappingNumbers {

	public static void main(String[] args) {
		int a=2;
		int b=25;
		System.out.println(" A is" + a + "and B is" + b);
		a= a+b;
		b= a-b;
		a= a-b;
		System.out.println("After Swapping A is" + a + "After Swapping B is" + b);
	

	}

}
